#!/usr/bin/env python3
# Generates programs/veyl_entry/src/bjj_consts.rs: Baby Jubjub constants for the on-chain arithmetic in bjj.rs.
# Field elements are in Montgomery form, radix 2^29, 9 limbs (R = 2^261). Internally the curve is used in its a = -1
# model (x' = s*x with s = sqrt(-a)), where the fast extended-coordinate formulas apply; points convert at the boundary.
# The fixed-base table: B8 * 16^k * j for k = 0..15, j = 1..8, in cached form (Y-X, Y+X, 2d'T, 2Z), Z = 1.
p = 21888242871839275222246405745257275088548364400416034343698204186575808495617
l = 2736030358979909402780800718157159386076813972158567259200215660948447373041
a, d = 168700, 168696
Bx = 5299619240641551281634865583518297030282874472190772894086521144482721001553
By = 16950150798460657717958625567821834550301663161624707787222815936182638968203
RB, N = 29, 9; R = 1 << (RB * N); M = (1 << RB) - 1
def limbs(x): return [(x >> (RB * i)) & M for i in range(N)]
def mont(x): return limbs(x * R % p)
def sqrt(n):  # Tonelli-Shanks
    q, s = p - 1, 0
    while q % 2 == 0: q //= 2; s += 1
    z = 2
    while pow(z, (p - 1) // 2, p) != p - 1: z += 1
    m, c, t, r = s, pow(z, q, p), pow(n, q, p), pow(n, (q + 1) // 2, p)
    while t != 1:
        i, t2 = 0, t
        while t2 != 1: t2 = t2 * t2 % p; i += 1
        b = pow(c, 1 << (m - i - 1), p); m, c, t, r = i, b * b % p, t * b * b % p, r * b % p
    return r
sq = sqrt((-a) % p); sq = min(sq, p - sq); assert sq * sq % p == (-a) % p
dp = (-d * pow(a, -1, p)) % p  # d' of the a = -1 model
inv = (-pow(p, -1, 1 << RB)) % (1 << RB)
def add(P, Q):  # original model, affine
    (x1, y1), (x2, y2) = P, Q; t = d * x1 * x2 * y1 * y2 % p
    return ((x1 * y2 + y1 * x2) * pow(1 + t, -1, p) % p, (y1 * y2 - a * x1 * x2) * pow(1 - t, -1, p) % p)
def mul(P, k):
    R_ = (0, 1)
    while k:
        if k & 1: R_ = add(R_, P)
        P = add(P, P); k >>= 1
    return R_
def cached(P):
    x = P[0] * sq % p; y = P[1]
    return [mont((y - x) % p), mont((y + x) % p), mont(2 * dp * x * y % p), mont(2)]
rows = []
for k in range(16):
    base = mul((Bx, By), 16 ** k)
    rows.append([cached(mul(base, j)) for j in range(1, 9)])
fmt = lambda v: '[' + ', '.join(str(x) for x in v) + ']'
out = ['// Generated by scripts/gen-bjj-consts.py. Do not edit.', '#![allow(clippy::unreadable_literal)]',
       f'pub const P: [u64; 9] = {fmt(limbs(p))};', f'pub const P4: [u64; 9] = {fmt(limbs(4 * p))};', f'pub const INV: u64 = {inv};',
       f'/// R^2 mod p (plain limbs): to_mont(x) = mul(x, R2)', f'pub const R2: [u64; 9] = {fmt(limbs(R * R % p))};',
       f'pub const ONE: [u64; 9] = {fmt(mont(1))};', f'pub const TWO: [u64; 9] = {fmt(mont(2))};',
       f'/// a and d of circomlib\'s model (on-curve check)', f'pub const CA: [u64; 9] = {fmt(mont(a))};', f'pub const CD: [u64; 9] = {fmt(mont(d))};',
       f'/// s = sqrt(-a): x\' = s*x maps to the a = -1 model; S_INV maps back', f'pub const S: [u64; 9] = {fmt(mont(sq))};', f'pub const S_INV: [u64; 9] = {fmt(mont(pow(sq, -1, p)))};',
       f'/// 2d\' of the a = -1 model', f'pub const D2: [u64; 9] = {fmt(mont(2 * dp % p))};',
       f'/// p - 2 (inversion exponent), little-endian u64 words', f'pub const PM2: [u64; 4] = {fmt([((p - 2) >> (64 * i)) & ((1 << 64) - 1) for i in range(4)])};',
       f'/// the subgroup order l, little-endian u64 words', f'pub const L: [u64; 4] = {fmt([(l >> (64 * i)) & ((1 << 64) - 1) for i in range(4)])};',
       f'/// B8 * 16^k * j (k = 0..15, j = 1..8), cached form [Y-X, Y+X, 2d\'T, 2Z] (Montgomery, u32 limbs)',
       'pub const BTAB: [[[[u32; 9]; 4]; 8]; 16] = [']
for r in rows: out.append('  [' + ', '.join('[' + ', '.join(fmt(c) for c in e) + ']' for e in r) + '],')
out.append('];')
open('programs/veyl_entry/src/bjj_consts.rs', 'w').write('\n'.join(out) + '\n')
print('ok', 's =', sq)
