#!/usr/bin/env node
// Converts a snarkjs verification key into the Rust constants groth16-solana expects. Default: zk/keys/withdraw_vkey.json
// (unchanged from the EVM build) -> programs/veyl_pool/src/vkey.rs. Phase 2: `--all` also writes the transact and position
// circuits' keys (zk/keys/{transact,position}_vkey.json -> programs/veyl_pool/src/vkey_{transact,position}.rs), Phase 3 the
// sealed-batch circuits' (swap, claim).
//
// The curve points are the same BN254 points the Solidity verifier was exported from; only the encoding differs.
//   G1 (alpha, IC[i])      = x || y, each 32 bytes big-endian
//   G2 (beta, gamma, delta) = x.c1 || x.c0 || y.c1 || y.c0, each 32 bytes big-endian (the EVM precompile order,
//                            i.e. the imaginary part first; snarkjs stores [c0, c1])
// Usage: node scripts/vkey-to-rust.js [vkey.json] [out.rs]  |  node scripts/vkey-to-rust.js --all
'use strict';
const fs = require('fs'); const path = require('path');
const R = (p) => path.join(__dirname, '..', p);
if (process.argv[2] === '--all') {
  for (const c of ['withdraw', 'transact', 'position', 'swap', 'claim']) require('child_process').execFileSync(process.execPath, [__filename, R('zk/keys/' + c + '_vkey.json'), R('programs/veyl_pool/src/' + (c === 'withdraw' ? 'vkey.rs' : 'vkey_' + c + '.rs'))], { stdio: 'inherit' });
  process.exit(0);
}
const src = process.argv[2] || R('zk/keys/withdraw_vkey.json');
const out = process.argv[3] || R('programs/veyl_pool/src/vkey.rs');
const vk = JSON.parse(fs.readFileSync(src, 'utf8'));
if (vk.protocol !== 'groth16' || vk.curve !== 'bn128') throw new Error('expected a groth16 / bn128 verification key');
const be32 = (s) => { const h = BigInt(s).toString(16).padStart(64, '0'); return [...Buffer.from(h, 'hex')]; };
const g1 = (p) => { if (p[2] !== '1') throw new Error('G1 point not affine'); return [...be32(p[0]), ...be32(p[1])]; };
const g2 = (p) => { if (p[2][0] !== '1' || p[2][1] !== '0') throw new Error('G2 point not affine'); return [...be32(p[0][1]), ...be32(p[0][0]), ...be32(p[1][1]), ...be32(p[1][0])]; };
const arr = (a, per = 16) => { const lines = []; for (let i = 0; i < a.length; i += per) lines.push('        ' + a.slice(i, i + per).join(', ') + ','); return lines.join('\n'); };
const n = vk.nPublic;
if (vk.IC.length !== n + 1) throw new Error('IC length mismatch');
const isWithdraw = path.basename(src) === 'withdraw_vkey.json';
const rs = `// Generated by scripts/vkey-to-rust.js from zk/keys/${path.basename(src)}. Do not edit by hand.
// ${isWithdraw ? 'Same BN254 curve points as the EVM Groth16 verifier (contracts/src/verifier/WithdrawVerifier.sol); the' : (/^(swap|claim)_/.test(path.basename(src)) ? 'Phase 3' : 'Phase 2') + ' circuit (zk/circuits/' + path.basename(src).replace('_vkey.json', '.circom') + '). The'} bytes are
// big-endian x || y for G1 and x.c1 || x.c0 || y.c1 || y.c0 for G2, which is what groth16-solana / the alt_bn128
// syscalls take. Public inputs: ${n}.
use groth16_solana::groth16::Groth16Verifyingkey;

pub const NR_PUBLIC_INPUTS: usize = ${n};

pub const VERIFYING_KEY: Groth16Verifyingkey = Groth16Verifyingkey {
    nr_pubinputs: ${n},
    vk_alpha_g1: [
${arr(g1(vk.vk_alpha_1))}
    ],
    vk_beta_g2: [
${arr(g2(vk.vk_beta_2))}
    ],
    vk_gamme_g2: [
${arr(g2(vk.vk_gamma_2))}
    ],
    vk_delta_g2: [
${arr(g2(vk.vk_delta_2))}
    ],
    vk_ic: &[
${vk.IC.map((p) => '        [\n' + arr(g1(p), 16).replace(/^ {8}/gm, '            ') + '\n        ],').join('\n')}
    ],
};
`;
fs.writeFileSync(out, rs);
console.log('wrote', out, '(' + n + ' public inputs, ' + vk.IC.length + ' IC points)');
